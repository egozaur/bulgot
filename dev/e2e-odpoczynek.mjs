// Bulgot: test e2e w Edge (puppeteer-core z folderu tools/pt). Wymaga serwera plików na porcie 8090 (patrz CLAUDE.md). Uruchom z folderu tools/pt: node <ścieżka do tego pliku> [katalog na zrzuty]
import puppeteer from 'file:///C:/Users/Kurczak/tools/pt/node_modules/puppeteer-core/lib/esm/puppeteer/puppeteer-core.js';
const EDGE = 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
const out = process.argv[2];
const b = await puppeteer.launch({ executablePath: EDGE, headless: 'new', args: ['--no-first-run'] });
const wait = ms => new Promise(r => setTimeout(r, ms));
const errs = [], fails = [];
const ok = (c, m) => { console.log((c ? 'OK   ' : 'FAIL ') + m); if (!c) fails.push(m); };
const p = await b.newPage();
p.on('pageerror', e => errs.push('PAGEERR ' + e.message)); p.on('console', m => { if (m.type() === 'error' && !/404/.test(m.text())) errs.push('CONSOLE ' + m.text()); });
await p.setViewport({ width: 1600, height: 900 });
await p.goto('http://localhost:8090/bulgot/?local=1', { waitUntil: 'networkidle0' });
await p.evaluate(() => { localStorage.clear(); localStorage.setItem('bulgot:intro', '1'); });
await p.reload({ waitUntil: 'networkidle0' }); await wait(300);
await p.click('[data-act=new]'); await wait(200);
await p.evaluate(() => document.querySelector('[data-act=setmode][data-v=full]').click());
await p.click('[data-act=start]'); await wait(500);
await p.evaluate(() => { const k = 'bulgot:local:player:run'; const r = JSON.parse(localStorage.getItem(k)); Object.assign(r, { round: 5, coins: 20, hp: 20, tiles: ['ziarno-mocy', 'zezowate-oko'], offer: ['zezowate-oko', 'jajeczny-granat', 'czujne-oko', 'pianie-grozy'] }); localStorage.setItem(k, JSON.stringify(r)); });
await p.reload({ waitUntil: 'networkidle0' }); await wait(300); await p.click('[data-act=resume]'); await wait(400);
await p.screenshot({ path: out + '/v-oferta-odpoczynek.png' });
const R = () => p.evaluate(() => { const r = window.__bulgot.run; return { hp: r.hp, coins: r.coins, rested: r.rested, phase: r.phase }; });
let s = await R();
ok(await p.evaluate(() => !!document.querySelector('[data-act=rest]:not([disabled])')), 'przycisk Odpoczynek aktywny przy niskim życiu');
await p.click('[data-act=rest]'); await wait(500);
let s2 = await R();
ok(s2.hp > s.hp && s2.coins === 16 && s2.rested, `odpoczynek: życie ${s.hp} -> ${s2.hp}, Ziarna ${s2.coins}`);
ok(await p.evaluate(() => document.querySelector('[data-act=rest]').disabled), 'po odpoczynku przycisk jest zablokowany do końca rundy');
await p.keyboard.press('1'); await wait(500);
ok((await R()).phase === 'fight', 'wybór kafelka po odpoczynku');
ok(await p.evaluate(() => !!document.querySelector('[data-act=rest]')), 'przycisk Odpoczynek jest też przed walką');
console.log(errs.length ? 'BŁĘDY:\n' + errs.join('\n') : 'brak błędów w konsoli');
console.log(fails.length ? 'NIEPOWODZENIA: ' + fails.length : 'WSZYSTKO OK');
await b.close();
